  private val index = builtIns.associateBy { it.id }

  fun byId(id: String): WoodSpecies? = index[id]

  private data class Flags(val oily: Boolean, val bleeds: Boolean, val irritant: Boolean)

  // Reasons double as the notes, so the rating explanation and the species notes never disagree.
  private fun species(
    id: String,
    name: String,
    botanical: String,
    janka: Int,
    raw: String,
    oiled: String,
    pore: PoreType,
    flags: Flags,
    edge: Rating,
    end: Rating,
    notes: List<String>,
  ): WoodSpecies {
    val reasons =
      if (edge == Rating.RECOMMENDED && end == Rating.RECOMMENDED) emptyList() else notes
    return WoodSpecies(
      id = id,
      name = name,
      botanicalName = botanical,
      jankaLbf = janka,
      raw = derivedTones(Rgb.hex(raw)),
      oiled = derivedTones(Rgb.hex(oiled)),
      poreType = pore,
      oily = flags.oily,
      bleedsColor = flags.bleeds,
      irritant = flags.irritant,
      suitability =
        Suitability(
          edgeGrain = GrainRating(edge, if (edge == Rating.RECOMMENDED) emptyList() else reasons),
          endGrain = GrainRating(end, if (end == Rating.RECOMMENDED) emptyList() else reasons),
        ),
      notes = notes,
    )
  }
}

/**
 * Built-ins plus the user's custom species; a custom id that clashes with a built-in is dropped.
 */
class Woods(customs: List<WoodSpecies>) {
  val all: List<WoodSpecies> =
    WoodCatalog.builtIns + customs.filter { WoodCatalog.byId(it.id) == null }.distinctBy { it.id }

  private val index = all.associateBy { it.id }

  fun byId(id: String): WoodSpecies? = index[id]
}
